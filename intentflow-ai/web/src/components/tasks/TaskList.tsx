// components/tasks/TaskList.tsx
'use client'
import { TaskCard } from './TaskCard'
import { Spinner } from '@/components/ui/Spinner'
import type { Task } from '@/types/task'

interface TaskListProps {
  tasks: Task[]
  loading?: boolean
  emptyMessage?: string
}

export function TaskList({ tasks, loading, emptyMessage = 'No tasks yet' }: TaskListProps) {
  if (loading) {
    return (
      <div className="flex items-center justify-center py-20">
        <Spinner size="lg" />
      </div>
    )
  }

  if (tasks.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center py-20 text-center">
        <div className="w-16 h-16 rounded-2xl bg-white/[0.03] border border-white/[0.06] flex items-center justify-center mb-4">
          <svg width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5" className="text-slate-600">
            <path d="M9 5H7a2 2 0 00-2 2v12a2 2 0 002 2h10a2 2 0 002-2V7a2 2 0 00-2-2h-2M9 5a2 2 0 002 2h2a2 2 0 002-2M9 5a2 2 0 012-2h2a2 2 0 012 2" />
          </svg>
        </div>
        <p className="text-slate-500 text-sm">{emptyMessage}</p>
        <p className="text-slate-600 text-xs mt-1">Use the AI input above to create your first task</p>
      </div>
    )
  }

  return (
    <div className="space-y-2">
      {tasks.map((task) => (
        <TaskCard key={task.id} task={task} />
      ))}
    </div>
  )
}
